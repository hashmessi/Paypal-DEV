"""Pydantic request and response schemas for Fulfillment Evidence Ingestion."""

from datetime import datetime
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field

from app.drift.models import GateEvaluation


class IngestEvidenceRequest(BaseModel):
    purchase_id: str
    source: str = Field(default="carrier", description="Source of telemetry: 'carrier' | 'merchant' | 'synthetic_console'")
    external_event_id: str = Field(..., description="External tracking or telemetry event identifier")
    trust_level: str = Field(default="CARRIER_TELEMETRY", description="CARRIER_TELEMETRY | MERCHANT_ATTESTATION | UNVERIFIED")
    is_synthetic: bool = Field(default=True, description="Whether event was generated by synthetic test harness")
    carrier_status: Optional[str] = Field(None, description="LABEL_CREATED | ACCEPTED | IN_TRANSIT | DELIVERED")
    sku: Optional[str] = Field(None, description="Physical fulfilled product SKU")
    condition: Optional[str] = Field(None, description="NEW | REFURBISHED | UNVERIFIED")
    color: Optional[str] = Field(None, description="Fulfilled product finish")
    eta: Optional[datetime] = Field(None, description="Carrier estimated arrival timestamp")
    raw_payload: Optional[Dict[str, Any]] = Field(default_factory=dict, description="Raw telemetry JSON bytes")


class IngestEvidenceResponse(BaseModel):
    status: str
    evidence_id: Optional[str] = None
    gate: Optional[GateEvaluation] = None

